//! `scripts/test-changed` (docs/implementing.md "The scoped loop"): which tests a change reaches.
//! Every test runs `--dry-run <base>` in a scratch workspace with cpd's crate graph and layout
//! (`core/` is `cpd-core`, `tui/` is `cpd-tui` on core, `cli/` is `cpd` on both, its integration
//! tests one binary `cli/tests/it/` with a module per file), holding a copy of the script and of
//! `scripts/cargo.sh`, and reads the one command it prints.

use crate::common;

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

use common::{output, TestEnv};

const SCRIPTS: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../scripts");

/// The cargo that built these tests (a toolchain's own binary, not rustup's proxy): the
/// script's `cargo metadata` runs it, with its `rustc` beside it on `PATH`.
const CARGO: &str = env!("CARGO");

/// The scratch workspace's files at the base commit (path, text).
const FILES: &[(&str, &str)] = &[
    ("Cargo.toml", "[workspace]\nresolver = \"3\"\nmembers = [\"core\", \"tui\", \"cli\"]\n"),
    ("core/Cargo.toml", "[package]\nname = \"cpd-core\"\nversion = \"0.1.0\"\nedition = \"2024\"\n"),
    ("core/src/lib.rs", "pub fn core() {}\n"),
    ("core/src/store/migrations/0001-initial.sql", "-- cpd-migration: additive\n"),
    (
        "tui/Cargo.toml",
        "[package]\nname = \"cpd-tui\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[dependencies]\ncpd-core = { path = \"../core\" }\n",
    ),
    ("tui/src/lib.rs", "pub fn tui() {}\n"),
    (
        "cli/Cargo.toml",
        "[package]\nname = \"cpd\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[dependencies]\ncpd-core = { path = \"../core\" }\ncpd-tui = { path = \"../tui\" }\n",
    ),
    ("cli/build.rs", "fn main() {}\n"),
    ("cli/src/main.rs", "fn main() {}\n"),
    ("cli/tests/it/main.rs", "mod common;\nmod alpha;\nmod beta;\n"),
    ("cli/tests/it/common/mod.rs", "pub fn helper() {}\n"),
    ("cli/tests/it/alpha.rs", "#[test]\nfn one() {}\n"),
    ("cli/tests/it/beta.rs", "#[test]\nfn two() {}\n"),
    (".config/nextest.toml", "[profile.default]\nfail-fast = false\n"),
    ("docs/notes.md", "# Notes\n"),
    // Lockfile version 3: `cargo metadata` keeps a lockfile's version, so the change of a test
    // to version 4 survives it (an added comment would not: cargo rewrites the file without it).
    (
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"cpd\"\nversion = \"0.1.0\"\ndependencies = [\n \"cpd-core\",\n \"cpd-tui\",\n]\n\n[[package]]\nname = \"cpd-core\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"cpd-tui\"\nversion = \"0.1.0\"\ndependencies = [\n \"cpd-core\",\n]\n",
    ),
];

/// A scratch git repo holding the workspace of [`FILES`] and `scripts/{test-changed,cargo.sh}`,
/// all committed; `base` is that commit.
struct Scratch {
    env: TestEnv,
    repo: PathBuf,
    base: String,
}

/// What the dry run printed: the full suite, or `-p` crates and `-E` filters.
#[derive(Debug, PartialEq, Eq)]
struct Selection {
    workspace: bool,
    packages: BTreeSet<String>,
    filters: Vec<String>,
}

fn crates(names: &[&str]) -> Selection {
    Selection { workspace: false, packages: names.iter().map(|n| n.to_string()).collect(), filters: Vec::new() }
}

fn module(name: &str) -> Selection {
    Selection { filters: vec![format!("test(/^{name}::/)")], ..crates(&["cpd"]) }
}

fn full_suite() -> Selection {
    Selection { workspace: true, packages: BTreeSet::new(), filters: Vec::new() }
}

struct Out {
    exit: i32,
    stdout: String,
    stderr: String,
}

impl Scratch {
    fn new() -> Scratch {
        let env = TestEnv::empty();
        let repo = env.git_repo("scratch");
        for (path, text) in FILES {
            write(&repo, path, text);
        }
        fs::create_dir_all(repo.join("scripts")).unwrap();
        for script in ["test-changed", "cargo.sh"] {
            fs::copy(Path::new(SCRIPTS).join(script), repo.join("scripts").join(script)).unwrap();
        }
        env.git(&repo, &["add", "-A"]);
        env.git(&repo, &["commit", "-q", "-m", "workspace"]);
        let base = env.git(&repo, &["rev-parse", "HEAD"]);
        Scratch { env, repo, base }
    }

    /// Adds a comment line to `path` (creating it), in the file's own syntax so that cargo
    /// still reads the workspace; uncommitted and unstaged.
    fn edit(&self, path: &str) {
        let comment = match Path::new(path).extension().and_then(|e| e.to_str()) {
            Some("rs") => "// changed",
            Some("toml") => "# changed",
            Some("sql") => "-- changed",
            Some("sh") => "# changed",
            _ => "changed",
        };
        let old = fs::read_to_string(self.repo.join(path)).unwrap_or_default();
        write(&self.repo, path, &format!("{old}{comment}\n"));
    }

    /// Writes `path` and commits it on top of the base.
    fn commit(&self, path: &str, text: &str) {
        write(&self.repo, path, text);
        self.env.git(&self.repo, &["add", "-A"]);
        self.env.git(&self.repo, &["commit", "-q", "-m", &format!("change {path}")]);
    }

    /// Commits a changed `path` (a line added; created when missing).
    fn commit_edit(&self, path: &str) {
        self.edit(path);
        self.env.git(&self.repo, &["add", "-A"]);
        self.env.git(&self.repo, &["commit", "-q", "-m", &format!("change {path}")]);
    }

    /// `scripts/test-changed --dry-run <base>`, run in the scratch repo.
    fn dry_run(&self) -> Out {
        let cargo_dir = Path::new(CARGO).parent().expect("cargo's directory");
        let path = std::env::join_paths(
            [self.env.bin(), cargo_dir.to_path_buf()].into_iter().chain(std::env::split_paths(&std::env::var_os("PATH").unwrap_or_default())),
        )
        .unwrap();
        let mut cmd = self.env.command(self.repo.join("scripts/test-changed"));
        cmd.args(["--dry-run", &self.base]).current_dir(&self.repo).env("CARGO", CARGO).env("PATH", path);
        let out = output(&mut cmd).unwrap();
        Out {
            exit: out.status.code().expect("test-changed exited"),
            stdout: String::from_utf8(out.stdout).unwrap(),
            stderr: String::from_utf8(out.stderr).unwrap(),
        }
    }

    /// The selection of a dry run that must print a command: exit 0 and exactly one line,
    /// `<...>scripts/cargo.sh nextest run` and then `--workspace`, `-p <crate>` and `-E <filter>` only.
    fn selection(&self) -> Selection {
        let out = self.dry_run();
        let what = format!("exit {}, stdout {:?}, stderr {:?}", out.exit, out.stdout, out.stderr);
        assert_eq!(out.exit, 0, "{what}");
        let line = out.stdout.strip_suffix('\n').unwrap_or_else(|| panic!("stdout is not one line: {what}"));
        assert!(!line.contains('\n'), "stdout is more than one line: {what}");
        let words = shell_words(line);
        assert!(
            words.len() >= 3 && words[0].ends_with("scripts/cargo.sh") && words[1] == "nextest" && words[2] == "run",
            "not a `scripts/cargo.sh nextest run` command: {what}"
        );
        let mut selection = Selection { workspace: false, packages: BTreeSet::new(), filters: Vec::new() };
        let mut rest = words[3..].iter();
        while let Some(word) = rest.next() {
            match word.as_str() {
                "--workspace" => selection.workspace = true,
                "-p" => {
                    let name = rest.next().unwrap_or_else(|| panic!("-p without a crate: {what}"));
                    assert!(selection.packages.insert(name.clone()), "-p {name} twice: {what}");
                }
                "-E" => selection.filters.push(rest.next().unwrap_or_else(|| panic!("-E without a filter: {what}")).clone()),
                other => panic!("unexpected argument {other:?}: {what}"),
            }
        }
        selection
    }

    /// The dry run of a change that reaches no Rust test: exit 0, nothing on stdout, and
    /// `test-changed: nothing to run` on stderr.
    fn assert_nothing_to_run(&self) {
        let out = self.dry_run();
        let what = format!("exit {}, stdout {:?}, stderr {:?}", out.exit, out.stdout, out.stderr);
        assert_eq!((out.exit, out.stdout.as_str()), (0, ""), "{what}");
        assert!(out.stderr.contains("test-changed: nothing to run"), "{what}");
    }
}

fn write(repo: &Path, path: &str, text: &str) {
    let file = repo.join(path);
    fs::create_dir_all(file.parent().unwrap()).unwrap();
    fs::write(file, text).unwrap();
}

/// Splits a printed shell command into words: blanks separate them, single and double quotes
/// group, a backslash outside single quotes escapes the next character.
fn shell_words(line: &str) -> Vec<String> {
    let mut words = Vec::new();
    let mut word: Option<String> = None;
    let mut chars = line.chars();
    while let Some(c) = chars.next() {
        match c {
            ' ' | '\t' => words.extend(word.take()),
            '\'' => {
                let w = word.get_or_insert_with(String::new);
                for q in chars.by_ref() {
                    if q == '\'' {
                        break;
                    }
                    w.push(q);
                }
            }
            '"' => {
                let w = word.get_or_insert_with(String::new);
                while let Some(q) = chars.next() {
                    match q {
                        '"' => break,
                        '\\' => w.extend(chars.next()),
                        _ => w.push(q),
                    }
                }
            }
            '\\' => word.get_or_insert_with(String::new).extend(chars.next()),
            _ => word.get_or_insert_with(String::new).push(c),
        }
    }
    words.extend(word);
    words
}

#[test]
fn a_core_change_runs_core_and_its_reverse_dependencies() {
    let s = Scratch::new();
    s.commit_edit("core/src/lib.rs");
    assert_eq!(s.selection(), crates(&["cpd-core", "cpd-tui", "cpd"]));
}

#[test]
fn a_tui_change_runs_tui_and_cli() {
    let s = Scratch::new();
    s.commit_edit("tui/src/lib.rs");
    assert_eq!(s.selection(), crates(&["cpd-tui", "cpd"]));
}

#[test]
fn a_cli_source_change_runs_cli_only() {
    let s = Scratch::new();
    s.commit_edit("cli/src/main.rs");
    assert_eq!(s.selection(), crates(&["cpd"]));
}

#[test]
fn a_change_to_one_integration_test_module_runs_that_module_only() {
    let s = Scratch::new();
    s.commit_edit("cli/tests/it/alpha.rs");
    assert_eq!(s.selection(), module("alpha"));
}

#[test]
fn a_change_to_the_shared_files_of_the_integration_tests_runs_the_whole_cli_crate() {
    for shared in ["cli/tests/it/main.rs", "cli/tests/it/common/mod.rs"] {
        let s = Scratch::new();
        s.commit_edit(shared);
        assert_eq!(s.selection(), crates(&["cpd"]), "{shared}");
    }
}

#[test]
fn uncommitted_changes_count_unstaged_staged_and_untracked() {
    let s = Scratch::new();

    s.edit("core/src/lib.rs");
    assert_eq!(s.selection(), crates(&["cpd-core", "cpd-tui", "cpd"]), "unstaged");
    s.env.git(&s.repo, &["checkout", "-q", "--", "."]);

    s.edit("cli/src/main.rs");
    s.env.git(&s.repo, &["add", "cli/src/main.rs"]);
    assert_eq!(s.selection(), crates(&["cpd"]), "staged");
    s.env.git(&s.repo, &["reset", "-q", "--hard"]);

    s.edit("tui/src/extra.rs");
    assert_eq!(s.selection(), crates(&["cpd-tui", "cpd"]), "untracked");
}

#[test]
fn each_root_level_input_falls_back_to_the_full_suite() {
    let cases: &[(&str, &dyn Fn(&Scratch))] = &[
        ("the root Cargo.toml", &|s| s.commit_edit("Cargo.toml")),
        ("Cargo.lock", &|s| {
            let lock = fs::read_to_string(s.repo.join("Cargo.lock")).unwrap();
            s.commit("Cargo.lock", &lock.replace("version = 3\n", "version = 4\n"));
        }),
        ("rust-toolchain.toml", &|s| s.commit("rust-toolchain.toml", "[toolchain]\nchannel = \"stable\"\n")),
        ("a build.rs", &|s| s.commit_edit("cli/build.rs")),
        (".config/", &|s| s.commit_edit(".config/nextest.toml")),
        ("a migration", &|s| s.commit("core/src/store/migrations/0002-next.sql", "-- cpd-migration: additive\n")),
        ("scripts/cargo.sh", &|s| s.commit_edit("scripts/cargo.sh")),
    ];
    for (input, change) in cases {
        let s = Scratch::new();
        change(&s);
        assert_eq!(s.selection(), full_suite(), "{input}");
    }
}

