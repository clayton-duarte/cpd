//! Makes the list of named migrations from `src/store/migrations/` (contract
//! §4.5 N1–N4): one `Named` per `<YYYYMMDDTHHMM>-<slug>.sql`, sorted by name,
//! with its `-- cpd-migration:` header parsed. A file of any other shape fails
//! the build. The numbered legacy files (`0001-initial.sql` …) are not listed:
//! the store module's frozen `LEGACY` constant owns them.
//!
//! A migration that needs more than SQL has a `<name>.rs` beside its `.sql`
//! with `pub fn run(conn, home)`; it is wired in as the migration's `run`.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

const DIR: &str = "src/store/migrations";

/// `<YYYYMMDDTHHMM>-<slug>`, the slug `[a-z][a-z0-9-]{0,39}`.
fn is_named(stem: &str) -> bool {
    let Some((stamp, slug)) = stem.split_once('-') else {
        return false;
    };
    let b = stamp.as_bytes();
    let stamp_ok = b.len() == 13
        && b[8] == b'T'
        && b.iter()
            .enumerate()
            .all(|(i, c)| i == 8 || c.is_ascii_digit());
    let mut chars = slug.chars();
    let slug_ok = (1..=40).contains(&slug.len())
        && chars.next().is_some_and(|c| c.is_ascii_lowercase())
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
    stamp_ok && slug_ok
}

/// `NNNN-<slug>`: a legacy name (contract §4.5 N2).
fn is_legacy(stem: &str) -> bool {
    stem.split_once('-').is_some_and(|(n, slug)| {
        n.len() == 4 && n.bytes().all(|c| c.is_ascii_digit()) && !slug.is_empty()
    })
}

/// The `Compat` expression of a migration's first line (N3).
fn compat(name: &str, sql: &str) -> String {
    let first = sql.lines().next().unwrap_or_default();
    match first.strip_prefix("-- cpd-migration: ") {
        Some("additive") => "Compat::Additive".to_owned(),
        Some(rest) => match rest
            .strip_prefix("breaking after ")
            .map(|n| n.parse::<u32>())
        {
            Some(Ok(_)) => "Compat::Breaking".to_owned(),
            _ => panic!(
                "{name}.sql: the header must be `-- cpd-migration: additive` or `-- cpd-migration: breaking after <n>`, not {first:?}"
            ),
        },
        None => panic!(
            "{name}.sql: the first line must be `-- cpd-migration: additive` or `-- cpd-migration: breaking after <n>`, not {first:?}"
        ),
    }
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={DIR}");
    let manifest =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let dir = manifest.join(DIR);

    // name -> (has .sql, has .rs)
    let mut found: BTreeMap<String, (bool, bool)> = BTreeMap::new();
    for entry in fs::read_dir(&dir).unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
    {
        let path = entry.expect("a directory entry").path();
        let file = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_default()
            .to_owned();
        let (stem, ext) = file.rsplit_once('.').unwrap_or((&file, ""));
        match ext {
            "sql" | "rs" if is_legacy(stem) => {
                assert!(
                    ext == "sql",
                    "{file}: a legacy migration has no Rust file here"
                );
            }
            "sql" | "rs" if is_named(stem) => {
                let slot = found.entry(stem.to_owned()).or_default();
                if ext == "sql" {
                    slot.0 = true
                } else {
                    slot.1 = true
                }
            }
            _ => panic!(
                "{DIR}/{file}: not a migration name `<YYYYMMDDTHHMM>-<slug>.sql` (UTC minute; slug [a-z][a-z0-9-]{{0,39}}) nor a legacy `NNNN-<slug>.sql`"
            ),
        }
    }

    let mut out = String::from(
        "/// Generated by `build.rs` from `migrations/`: every named migration, by name.\n",
    );
    out.push_str("pub(super) const NAMED: &[Named] = &[\n");
    let mut modules = String::new();
    for (index, (name, (sql, rust))) in found.iter().enumerate() {
        assert!(*sql, "{DIR}/{name}.rs has no {name}.sql beside it");
        let text =
            fs::read_to_string(dir.join(format!("{name}.sql"))).expect("a readable migration");
        let compat = compat(name, &text);
        let run = if *rust {
            writeln!(
                modules,
                "mod named_{index} {{ include!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{DIR}/{name}.rs\")); }}"
            )
            .unwrap();
            format!("Some(named_{index}::run)")
        } else {
            "None".to_owned()
        };
        writeln!(
            out,
            "    Named {{ name: {name:?}, compat: {compat}, sql: include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{DIR}/{name}.sql\")), run: {run} }},"
        )
        .unwrap();
    }
    out.push_str("];\n");
    out.push_str(&modules);
    let target =
        PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR")).join("migrations.rs");
    fs::write(&target, out).unwrap_or_else(|e| panic!("cannot write {}: {e}", target.display()));
}
