//! `cpd version sync` and the migration it follows, ported from `cli/tests/tooling/version.rs` (the exec tests of
//! `scripts/sync-version.sh` and `scripts/new-migration.sh`): a temp dir for the files, `Fakes` for the ports.

use std::fs;
use std::path::{Path, PathBuf};

use super::{new_migration, sync};
use crate::ports::Fakes;

const FIXTURE_CARGO_TOML: &str = "[workspace]\nmembers = [\"cli\"]\n\n[workspace.package]\nversion = \"0.0.5\"\nedition = \"2024\"\n\n[workspace.dependencies]\nfoo = { version = \"0.0.5\" }\n\n[profile.dev]\ndebug = 0\n";

fn fixture_cargo_lock() -> String {
    let mut s = String::from("# This file is automatically @generated by Cargo.\nversion = 4\n");
    for name in ["cpd", "cpd-core", "cpd-engine", "cpd-tui"] {
        s.push_str(&format!(
            "\n[[package]]\nname = \"{name}\"\nversion = \"0.0.5\"\n"
        ));
    }
    s.push_str("\n[[package]]\nname = \"other\"\nversion = \"0.0.5\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\n");
    s
}

/// A fake repo root with kind.rs (PROTOCOL 7), three `.sql` files and one `.rs`, Cargo.toml and Cargo.lock.
fn fixture() -> (tempfile::TempDir, PathBuf) {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().join("fixture");
    let migrations = root.join("core/src/store/migrations");
    fs::create_dir_all(&migrations).unwrap();
    fs::create_dir_all(root.join("core/src/events")).unwrap();
    fs::write(
        root.join("core/src/events/kind.rs"),
        "//! kinds\n\npub const PROTOCOL: u32 = 7;\npub const OTHER: u32 = 9;\n",
    )
    .unwrap();
    for f in [
        "0001-initial.sql",
        "0002-a.sql",
        "20261018T0828-b.sql",
        "20261018T0828-b.rs",
    ] {
        fs::write(migrations.join(f), "-- cpd-migration: additive\n").unwrap();
    }
    fs::write(root.join("Cargo.toml"), FIXTURE_CARGO_TOML).unwrap();
    fs::write(root.join("Cargo.lock"), fixture_cargo_lock()).unwrap();
    (dir, root)
}

fn read(root: &Path, file: &str) -> String {
    fs::read_to_string(root.join(file)).unwrap()
}

fn assert_untouched(root: &Path, what: &str) {
    assert_eq!(read(root, "Cargo.toml"), FIXTURE_CARGO_TOML, "{what}");
    assert_eq!(read(root, "Cargo.lock"), fixture_cargo_lock(), "{what}");
}

#[test]
fn sync_print_derives_the_version_from_kind_rs_and_the_sql_files() {
    let (_dir, root) = fixture();
    assert_eq!(sync(&root, true), Ok("0.7.3".to_owned()));
    assert_untouched(&root, "--print writes nothing");
}

#[test]
fn sync_rewrites_cargo_toml_and_the_workspace_members_of_cargo_lock() {
    let (_dir, root) = fixture();
    let line = sync(&root, false).unwrap();
    assert_eq!(line, "sync-version: 0.7.3");
    let toml = read(&root, "Cargo.toml");
    assert_eq!(
        toml,
        FIXTURE_CARGO_TOML.replacen(
            "version = \"0.0.5\"\nedition",
            "version = \"0.7.3\"\nedition",
            1
        )
    );
    assert!(toml.contains("foo = { version = \"0.0.5\" }\n"));
    let mut lock = fixture_cargo_lock();
    for name in ["cpd", "cpd-core", "cpd-engine", "cpd-tui"] {
        lock = lock.replacen(
            &format!("name = \"{name}\"\nversion = \"0.0.5\""),
            &format!("name = \"{name}\"\nversion = \"0.7.3\""),
            1,
        );
    }
    assert_eq!(read(&root, "Cargo.lock"), lock);
    assert!(lock.contains("name = \"other\"\nversion = \"0.0.5\""));
}

#[test]
fn sync_is_idempotent() {
    let (_dir, root) = fixture();
    sync(&root, false).unwrap();
    let (toml, lock) = (read(&root, "Cargo.toml"), read(&root, "Cargo.lock"));
    assert!(
        toml.contains("version = \"0.7.3\""),
        "first run rewrote nothing: {toml}"
    );
    assert_eq!(sync(&root, false), Ok("sync-version: 0.7.3".to_owned()));
    assert_eq!(read(&root, "Cargo.toml"), toml);
    assert_eq!(read(&root, "Cargo.lock"), lock);
}

#[test]
fn sync_without_a_protocol_line_fails_and_changes_nothing() {
    let (_dir, root) = fixture();
    let kind = root.join("core/src/events/kind.rs");
    let check = |what: &str, expected: String| {
        assert_eq!(sync(&root, false), Err(expected), "{what}");
        assert_untouched(&root, what);
        assert!(sync(&root, true).is_err(), "{what}: --print fails too");
    };
    fs::write(&kind, "//! kinds\npub const OTHER: u32 = 9;\n").unwrap();
    check(
        "no PROTOCOL line",
        format!(
            "sync-version: no 'pub const PROTOCOL: u32 = <n>;' line in {}.",
            kind.display()
        ),
    );
    fs::write(&kind, "pub const PROTOCOL: u32 = 7;\n").unwrap();
    let migrations = root.join("core/src/store/migrations");
    for e in fs::read_dir(&migrations).unwrap() {
        let p = e.unwrap().path();
        if p.extension().is_some_and(|x| x == "sql") {
            fs::remove_file(p).unwrap();
        }
    }
    check(
        "no .sql file",
        format!("sync-version: no .sql file in {}.", migrations.display()),
    );
}

#[test]
fn sync_without_a_workspace_package_fails_and_changes_nothing() {
    let (_dir, root) = fixture();
    let toml = root.join("Cargo.toml");
    let text = "[workspace]\nmembers = [\"cli\"]\n";
    fs::write(&toml, text).unwrap();
    assert_eq!(
        sync(&root, false),
        Err(format!(
            "sync-version: no [workspace.package] in {}.",
            toml.display()
        ))
    );
    assert_eq!(read(&root, "Cargo.toml"), text);
    assert_eq!(read(&root, "Cargo.lock"), fixture_cargo_lock());
}

#[test]
fn sync_without_a_version_line_under_workspace_package_fails_and_changes_nothing() {
    let (_dir, root) = fixture();
    let toml = root.join("Cargo.toml");
    let text = "[workspace.package]\nedition = \"2024\"\n\n[workspace.dependencies]\nfoo = { version = \"0.0.5\" }\nversion = \"0.0.5\"\n";
    fs::write(&toml, text).unwrap();
    assert_eq!(
        sync(&root, false),
        Err(format!(
            "sync-version: no version line under [workspace.package] in {}.",
            toml.display()
        ))
    );
    assert_eq!(read(&root, "Cargo.toml"), text);
    assert_eq!(read(&root, "Cargo.lock"), fixture_cargo_lock());
}

#[test]
fn new_migration_runs_the_sync() {
    let (_dir, root) = fixture();
    let fakes = Fakes::new();
    let file = new_migration(&fakes.ports, &root, "demo").unwrap();
    let shown = file.to_string_lossy().into_owned();
    assert!(
        shown.contains("core/src/store/migrations/")
            && shown.ends_with("-demo.sql")
            && file.is_file(),
        "{shown}"
    );
    assert_eq!(
        file.file_name().unwrap(),
        "20260101T0000-demo.sql",
        "the UTC minute of the clock"
    );
    assert_eq!(
        fs::read_to_string(&file).unwrap(),
        "-- cpd-migration: additive\n"
    );
    assert!(
        read(&root, "Cargo.toml").contains("version = \"0.7.4\"\nedition"),
        "{}",
        read(&root, "Cargo.toml")
    );
    assert!(fakes.runner.calls().is_empty(), "no process runs");
}

#[test]
fn sync_agrees_with_the_rust_constants() {
    let repo = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let migrations = fs::read_dir(repo.join("core/src/store/migrations"))
        .unwrap()
        .filter_map(Result::ok)
        .filter(|e| e.path().is_file() && e.path().extension().is_some_and(|x| x == "sql"))
        .count();
    assert_eq!(
        sync(&repo, true),
        Ok(format!("0.{}.{}", crate::events::PROTOCOL, migrations))
    );
}
