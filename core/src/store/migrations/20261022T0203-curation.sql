-- Record curation and retirement (hs-d549, hs-d551): `record_retirements` (a proposal to take a record out of force, and
-- the User's decision), `record_curations` (a record's topic and short form, and its doc candidacy), the Inbox kinds
-- `curate-retire` and `curate-docs` (`inbox_items` rebuilt with them in its check, as `distill-tier` did: every row keeps
-- its id; the copy writes no history row) and the Event kinds `records-retired`, `docs-decided`, `context-curated`. The
-- history triggers and the `_no_delete` triggers of the new tables are generated by the runner's reconcile.
CREATE TABLE record_retirements (
  context      TEXT NOT NULL REFERENCES contexts(id),
  record       TEXT NOT NULL,
  reason       TEXT NOT NULL CHECK (reason IN ('duplicate', 'superseded', 'documented')),
  target       TEXT NOT NULL CHECK (length(target) >= 1),
  status       TEXT NOT NULL CHECK (status IN ('pending', 'approved', 'rejected')),
  proposed_at  TEXT NOT NULL,
  decided_at   TEXT,
  decided_by   TEXT,
  PRIMARY KEY (context, record),
  FOREIGN KEY (context, record) REFERENCES context_records(context, id),
  CHECK ((status = 'pending') = (decided_at IS NULL)),
  CHECK ((decided_at IS NULL) = (decided_by IS NULL))
) STRICT;
CREATE TABLE record_curations (
  context       TEXT NOT NULL REFERENCES contexts(id),
  record        TEXT NOT NULL,
  topic         TEXT NOT NULL CHECK (length(topic) BETWEEN 1 AND 40),
  short         TEXT NOT NULL CHECK (length(CAST(short AS BLOB)) BETWEEN 1 AND 120),
  doc_candidate TEXT CHECK (doc_candidate IN ('pending', 'sent', 'dismissed')),
  doc_paths     TEXT CHECK (doc_paths IS NULL OR (json_valid(doc_paths) AND json_type(doc_paths) = 'array')),
  curated_at    TEXT NOT NULL,
  PRIMARY KEY (context, record),
  FOREIGN KEY (context, record) REFERENCES context_records(context, id)
) STRICT;
