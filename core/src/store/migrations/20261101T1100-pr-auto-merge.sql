-- cpd-migration: additive
-- The auto-merge request of a posted PR (pro-d115, pro-d117; commands.md §9.8b; contract §4.4): `auto_merge` is `none` (nothing
-- requested: a row from before this migration, or a repo that does not allow auto-merge), `pending` (to send or retry),
-- `enabled` or `refused`; `auto_merge_at` is set exactly when it is `enabled` or `refused`. `ALTER TABLE` cannot add the
-- table CHECK that ties the two columns, so `pr_posts` is rebuilt as `provider-error-cause` rebuilt `attempts`: the same
-- definition plus the two columns, a copy of every row (the new ones `none`, NULL), `DROP`, `RENAME`. The copy writes no
-- `history` row; the history triggers (dropped with the table) are regenerated by the runner's reconcile.
CREATE TABLE pr_posts_new (
  plan        TEXT NOT NULL REFERENCES plans(id),
  pr          TEXT NOT NULL,
  channel     TEXT NOT NULL CHECK (length(channel) BETWEEN 1 AND 20),
  ts          TEXT NOT NULL CHECK (length(ts) >= 1),
  link        TEXT NOT NULL CHECK (length(link) >= 1),
  posted_at   TEXT NOT NULL,
  reaction    TEXT CHECK (reaction IS NULL OR length(reaction) BETWEEN 1 AND 100),
  reacted_at  TEXT,
  auto_merge  TEXT NOT NULL DEFAULT 'none' CHECK (auto_merge IN ('none','pending','enabled','refused')),
  auto_merge_at TEXT,
  PRIMARY KEY (plan, pr),
  FOREIGN KEY (plan, pr) REFERENCES prs(plan, key),
  CHECK (reaction IS NOT NULL OR reacted_at IS NULL),
  CHECK ((auto_merge IN ('enabled','refused')) = (auto_merge_at IS NOT NULL))
) STRICT;
INSERT INTO pr_posts_new (plan, pr, channel, ts, link, posted_at, reaction, reacted_at)
  SELECT plan, pr, channel, ts, link, posted_at, reaction, reacted_at FROM pr_posts;
DROP TABLE pr_posts;
ALTER TABLE pr_posts_new RENAME TO pr_posts;
