import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { run as prOpen } from "../../src/commands/pr-open.ts";
import { run as prPoll } from "../../src/commands/pr-poll.ts";
import { gitOut } from "../../src/git/git.ts";
import { getPhase, readWorkflow } from "../../src/ledger/workflow.ts";
import { CpdError } from "../../src/lib/errors.ts";
import { ledgerDir, prStatePath } from "../../src/lib/paths.ts";
import { commitFile } from "../git/fixtures.ts";
import { PR_URL, dispatchedWorkflow, fakeGh, sandboxCpd, viewJson } from "./setup.ts";

sandboxCpd();
const gh = fakeGh();

const messages = (queueDir: string) =>
  readdirSync(queueDir).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(readFileSync(join(queueDir, f), "utf8")));

async function code(p: Promise<unknown>): Promise<{ code: string; exit: number; details: Record<string, unknown> }> {
  try {
    await p;
  } catch (e) {
    if (e instanceof CpdError) return { code: e.code, exit: e.exitCode, details: e.details };
    throw e;
  }
  assert.fail("expected a CpdError");
}

test("pr open refuses while a Job is not closed or cancelled, and does not push or call gh pr create", async () => {
  const f = await dispatchedWorkflow("open-refused", { jobs: ["a"], extra: ["b"] });
  const before = gh.calls().length;
  const r = await code(prOpen(["--wf", f.wf]));
  assert.deepEqual([r.code, r.exit], ["jobs_not_finished", 3]);
  assert.deepEqual(r.details.jobs, [{ key: "b", status: "queued" }]);
  assert.equal(gh.calls().length, before);
  assert.equal(await gitOut(f.repo, ["ls-remote", f.origin, "refs/heads/cpd/open-refused"]), "");
  assert.equal(await getPhase(f.wf), "dispatch");
  assert.equal(readWorkflow(f.wf).pr, null);
});

test("pr open pushes the Lead Branch, calls gh pr create with the exact argv, records the PR and moves to phase pr", async () => {
  const f = await dispatchedWorkflow("open-ok");
  await commitFile(f.leadWorktree, "feature.txt", "x\n", "lead: feature");
  const before = gh.calls().length;
  const r: any = await prOpen(["--wf", f.wf]);

  assert.equal(r.ok, true);
  assert.equal(r.pr.number, 7);
  assert.equal(r.pr.url, PR_URL);
  const head = await gitOut(f.leadWorktree, ["rev-parse", "HEAD"]);
  assert.match(await gitOut(f.repo, ["ls-remote", f.origin, "refs/heads/cpd/open-ok"]), new RegExp(`^${head}\\s`));
  assert.equal(await gitOut(f.leadWorktree, ["rev-parse", "--abbrev-ref", "@{upstream}"]), "origin/cpd/open-ok");

  const create = gh.calls().slice(before).find((c) => c[0] === "pr" && c[1] === "create")!;
  assert.deepEqual(create.slice(0, 9), ["pr", "create", "--base", "main", "--head", "cpd/open-ok", "--title", "Workflow open-ok", "--body"]);
  const body = create[9]!;
  assert.match(body, /^# Workflow open-ok\n/);
  assert.match(body, /\| a \| Job a \| closed \| - \|/);
  assert.match(body, /\| b \| Job b \| closed \| - \|/);
  assert.match(body, /Generated by cpd\n$/);

  assert.equal(await getPhase(f.wf), "pr");
  const pr = readWorkflow(f.wf).pr!;
  assert.deepEqual([pr.number, pr.url], [7, PR_URL]);
  assert.ok(!Number.isNaN(Date.parse(pr.openedAt)));
});

test("pr poll sequence: nothing, one pr-feedback, nothing again, then merged", async () => {
  const f = await dispatchedWorkflow("poll-seq");
  await prOpen(["--wf", f.wf]);
  const poll = (): Promise<any> => prPoll(["--wf", f.wf]);

  // 1. no feedback: no message
  assert.deepEqual((await poll()).changes, []);
  assert.deepEqual(messages(f.queueDir), []);
  assert.equal(JSON.parse(readFileSync(prStatePath(f.wf), "utf8")).number, 7);

  // 2. a failing check (and a passing one) plus two review comments: one pr-feedback with exactly those
  const long = "x".repeat(2500);
  gh.set("view", viewJson({ statusCheckRollup: [{ name: "build", conclusion: "FAILURE" }, { name: "lint", conclusion: "SUCCESS" }] }));
  gh.set("comments", [
    { id: 11, user: { login: "rev" }, path: "src/a.ts", line: 3, body: "rename this" },
    { id: 12, user: { login: "rev" }, path: "src/b.ts", line: null, body: long },
  ]);
  await poll();
  const [m, ...rest] = messages(f.queueDir);
  assert.equal(rest.length, 0);
  assert.equal(m.kind, "pr-feedback");
  assert.deepEqual(m.data.checks, [{ type: "check", name: "build", conclusion: "FAILURE" }]);
  assert.deepEqual(m.data.reviews, []);
  assert.deepEqual(m.data.comments, [
    { type: "comment", id: "11", author: "rev", path: "src/a.ts", line: 3, body: "rename this" },
    { type: "comment", id: "12", author: "rev", path: "src/b.ts", line: null, body: "x".repeat(2000) },
  ]);

  // 3. the same state: no new message
  await poll();
  assert.equal(messages(f.queueDir).length, 1);

  // a new review is the only new thing: one more message with only it
  gh.set("view", viewJson({
    statusCheckRollup: [{ name: "build", conclusion: "FAILURE" }, { name: "lint", conclusion: "SUCCESS" }],
    reviews: [{ id: "PRR_1", author: { login: "rev" }, state: "CHANGES_REQUESTED", body: "no" }],
  }));
  await poll();
  const all = messages(f.queueDir);
  assert.equal(all.length, 2);
  assert.deepEqual(all[1].data.reviews, [{ type: "review", id: "PRR_1", author: "rev", state: "CHANGES_REQUESTED", body: "no" }]);
  assert.deepEqual([all[1].data.checks, all[1].data.comments], [[], []]);

  // 4. merged: workflow-done, phase done, freeze marker
  gh.set("view", viewJson({ state: "MERGED", mergedAt: "2026-01-02T00:00:00Z" }));
  assert.equal(existsSync(join(ledgerDir(f.wf), "MIGRATION-FREEZE")), false);
  assert.equal((await poll()).merged, true);
  assert.equal(messages(f.queueDir).at(-1).kind, "workflow-done");
  assert.equal(messages(f.queueDir).length, 3);
  assert.equal(existsSync(join(ledgerDir(f.wf), "MIGRATION-FREEZE")), true);
  assert.equal(await getPhase(f.wf), "done");
});

