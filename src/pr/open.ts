const cell = (s: string): string => s.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");

/** PR body: Workflow title, the Jobs table (key, title, status, merged SHA), and the generator line. */
export function prBody(title: string, jobs: Job[]): string {
  const rows = jobs.map((j) => {
    const sha = j.metadata.merged_sha;
    return `| ${cell(j.key)} | ${cell(j.title)} | ${j.status} | ${typeof sha === "string" ? `\`${sha}\`` : "-"} |`;
  });
  return [`# ${title}`, "", "| Job | Title | Status | Merged SHA |", "| --- | --- | --- | --- |", ...rows, "", "Generated by cpd", ""].join("\n");
}

/** The Gate (`wt hook pre-merge`) on the Lead Branch: a failure refuses `gate_failed` (exit 3, last 60 lines) and the caller pushes nothing; any other failure is `gate_error`. */
export async function requireGate(leadWorktree: string): Promise<void> {
  const gate = await runGate(leadWorktree, "pre-merge");
  if (!gate.passed) {
    throw refused("gate_failed", `the Gate failed on the Lead Branch (exit ${gate.exitCode}); add fix Jobs and try again`, {
      exitCode: gate.exitCode,
      outputTail: gate.outputTail,
    });
  }
}

/** Contract §11 `pr open`. */
export async function openPr(wf: string): Promise<NonNullable<WorkflowJson["pr"]>> {
  const w = readWorkflow(wf);
  const phase = await getPhase(wf);
  if (phase !== "dispatch") throw refused("illegal_phase", `pr open needs phase dispatch, not ${phase}`, { phase });
  if (w.leadWorktree === null) throw refused("no_lead_worktree", `Workflow ${wf} has no Lead worktree`, { wf });
  const jobs = await listJobs(wf);
  const open = jobs.filter((j) => j.status !== "closed" && j.status !== "cancelled");
  if (open.length > 0) {
    throw refused("jobs_not_finished", "every Job must be closed or cancelled before opening the PR", { jobs: open.map((j) => ({ key: j.key, status: j.status })) });
  }
  if (!jobs.some((j) => j.status === "closed")) throw refused("nothing_merged", "no Job is closed (merged); there is nothing to open a PR for", { wf });

  await requireGate(w.leadWorktree);

  const push = await git(w.leadWorktree, ["push", "-u", "origin", w.leadBranch]);
  if (push.code !== 0) throw failure("git_push_failed", `git push exited ${push.code ?? push.signal}`, { stderr: tail(push.stderr) });

  const { number, url } = await createPr(w.repo, { base: w.base, head: w.leadBranch, title: w.title, body: prBody(w.title, jobs) });
  const pr = { number, url, openedAt: new Date().toISOString() };
  await writeWorkflow(wf, { ...readWorkflow(wf), pr });
  await setPhase(wf, "pr");
  logEvent(wf, "info", "pr_opened", { number, url });
  return pr;
}
